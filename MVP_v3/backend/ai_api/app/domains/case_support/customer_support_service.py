def _unsupported_customer_ui_guidance(content: str, capabilities: list[str]) -> bool:
    normalized = re.sub(r"\s+", " ", content).strip()
    if _LEGACY_TRANSACTION_UI_RE.search(normalized):
        return True
    if "OPEN_ACTIVE_QUESTION" not in capabilities and re.search(
        r"(?:확인|질문)\s*카드.{0,20}(?:누르|열|선택|이동)|(?:누르|열|선택).{0,20}(?:확인|질문)\s*카드",
        normalized,
    ):
        return True
    if "OPEN_RECOVERY_GUIDE" not in capabilities and re.search(
        r"(?:피해구제|피해\s*대응)\s*(?:안내|화면|메뉴).{0,20}(?:누르|열|선택|이동)|"
        r"(?:누르|열|선택|이동).{0,20}(?:피해구제|피해\s*대응)\s*(?:안내|화면|메뉴)",
        normalized,
    ):
        return True
    return False


def _unverified_phone_numbers(content: str) -> bool:
    allowed = {contact["number"] for contact in CUSTOMER_SAFETY_CONTACTS}
    return any(re.sub(r"\D", "", number) not in allowed for number in _PHONE_NUMBER_RE.findall(content))


class CustomerSupportService:
    async def generate(self, request: CaseCopilotInput) -> CaseCopilotOutput:
        if len(request.prompt.strip()) > int(os.getenv("CASE_COPILOT_MAX_INPUT_CHARS", "6000")):
            raise ValueError("AI 요청은 6,000자 이하로 입력해 주세요.")
        if not os.getenv("OPENAI_API_KEY"):
            raise CaseCopilotAuthenticationError("OPENAI_API_KEY가 설정되지 않아 실제 AI 서버에 연결할 수 없습니다.")

        model = (
            os.getenv("OPENAI_CUSTOMER_SUPPORT_MODEL")
            or os.getenv("OPENAI_CASE_COPILOT_MODEL", "gpt-5.6-luna")
        )
        provider_input = (
            f"고객 공개 사건 맥락:\n{_customer_context(request)}\n\n"
            f"[고객의 현재 질문]\n{request.prompt.strip()}"
        )
        client = AsyncOpenAI(
            api_key=os.environ["OPENAI_API_KEY"],
            timeout=float(os.getenv("OPENAI_TIMEOUT_SECONDS", "20")),
            max_retries=0,
        )
        try:
            await _customer_support_budget.reserve(request.case_id)
            async with _customer_support_concurrency:
                response = await client.responses.create(
                    model=model,
                    instructions=_customer_instructions(),
                    input=provider_input,
                    max_output_tokens=int(os.getenv("OPENAI_CUSTOMER_AI_MAX_OUTPUT_TOKENS", "250")),
                )
        except RateLimitError as exc:
            raise CaseCopilotQuotaError("OpenAI 사용 한도 또는 요청 한도에 도달해 AI 답변을 만들지 못했습니다.") from exc
        except AuthenticationError as exc:
            raise CaseCopilotAuthenticationError("OpenAI 인증에 실패해 실제 AI 서버에 연결할 수 없습니다.") from exc
        except (CaseCopilotQuotaError, CaseCopilotAuthenticationError):
            raise
        except Exception as exc:
            logger.exception(
                "CustomerSupport provider call failed: type=%s model=%s",
                type(exc).__name__, model,
            )
            raise CaseCopilotProviderError("실제 AI 서버에 연결하지 못해 답변을 생성하지 못했습니다. 잠시 후 다시 시도해 주세요.") from exc

        raw_content = (getattr(response, "output_text", None) or "").strip()
        if getattr(response, "status", None) == "incomplete" or not raw_content:
            raise CaseCopilotResponseError("AI가 답변을 완성하지 못했습니다. 잠시 후 다시 시도해 주세요.")
        content = user_text(raw_content)
        if not content:
            raise CaseCopilotResponseError("AI 서버가 빈 응답을 반환해 답변을 생성하지 않았습니다.")

        sections = _customer_context(request)
        quality = CopilotQualityEvaluator.evaluate(
            assistant_mode="CUSTOMER_SUPPORT",
            prompt=request.prompt,
            response=content,
            context=(sections,),
            grounding_context=(
                *request.known_facts,
                *request.customer_progress,
                *request.published_verification_results,
                *request.retrieved_context,
            ),
        )
        blocking = CopilotQualityEvaluator.runtime_blocking_failures(quality)
        if blocking or _unsupported_customer_ui_guidance(content, request.customer_ui_capabilities) or _unverified_phone_numbers(content):
            logger.warning(
                "CustomerSupport quality blocked: criteria=%s unsupported_ui=%s unverified_phone=%s",
                ",".join(item.criterion for item in blocking) or "none",
                _unsupported_customer_ui_guidance(content, request.customer_ui_capabilities),
                _unverified_phone_numbers(content),
            )
            return CaseCopilotOutput(
                content=(
                    "현재 기록만으로는 정확히 확인하기 어렵습니다. 현재 화면에 표시된 질문이 있다면 알고 있는 범위에서 답해 주세요. "
                    "비밀번호나 인증번호 같은 실제 비밀 정보는 입력하지 마세요."
                ),
                model_mode="CUSTOMER_SUPPORT_SAFE_FALLBACK",
            )
        return CaseCopilotOutput(content=content, model_mode=model)
