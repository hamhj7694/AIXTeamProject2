# Contact details are owned by the service, not generated by the model. The
# public-channel references are maintained from police and FSC guidance:
# https://www.police.go.kr/www/agency/intro/intro0601.jsp
# https://www.fsc.go.kr/no040101?cnId=2953&curPage=3&pastPage=2&srchKey=sj&srchText=%EC%83%9D%EC%82%B0%EC%A0%81
CUSTOMER_SAFETY_CONTACTS = (
    {"label": "경찰 긴급 신고", "number": "112"},
    {"label": "금융감독원 문의", "number": "1332"},
)

_PHONE_NUMBER_RE = re.compile(r"(?<!\d)(?:0\d{1,2}[- .]?\d{3,4}[- .]?\d{4}|1[568]\d{2}[- .]?\d{4})(?!\d)")
_LEGACY_TRANSACTION_UI_RE = re.compile(
    r"(?:거래\s*내역|송금\s*내역|계좌\s*거래)\s*(?:조회|검색)\s*(?:화면|페이지|메뉴|버튼|기능)|"
    r"(?:거래\s*조회|송금\s*조회)\s*(?:화면|페이지|메뉴|버튼|기능)|/judge(?:/|\b)",
    re.IGNORECASE,
)


class CustomerSupportCallBudget:
    """Per-process request cap; production deployments should also use a shared quota."""

    def __init__(self) -> None:
        self._calls: dict[str, deque[float]] = defaultdict(deque)
        self._lock = asyncio.Lock()

    async def reserve(self, case_id: str) -> None:
        per_minute = max(1, int(os.getenv("CUSTOMER_AI_MAX_CALLS_PER_MINUTE", "6")))
        per_day = max(per_minute, int(os.getenv("CUSTOMER_AI_MAX_CALLS_PER_DAY", "40")))
        now = asyncio.get_running_loop().time()
        async with self._lock:
            calls = self._calls[case_id]
            while calls and now - calls[0] >= 86_400:
                calls.popleft()
            if len(calls) >= per_day:
                raise CaseCopilotQuotaError("이 Case의 오늘 고객 AI 상담 한도에 도달했습니다. 은행 담당자에게 연결해 주세요.")
            if sum(1 for called_at in calls if now - called_at < 60) >= per_minute:
                raise CaseCopilotQuotaError("AI 상담 요청이 연속으로 접수되었습니다. 잠시 후 다시 시도해 주세요.")
            calls.append(now)


_customer_support_budget = CustomerSupportCallBudget()
_customer_support_concurrency = asyncio.Semaphore(max(1, int(os.getenv("CUSTOMER_AI_MAX_CONCURRENCY", "2"))))


def _customer_context(request: CaseCopilotInput) -> str:
    """Construct model context from customer-visible fields only."""
    sections: list[tuple[str, list[str]]] = [
        ("현재 고객 화면에 표시 중인 확인 질문", [
            question.model_dump_json(exclude={"question_id"})
            for question in request.customer_service_questions
            if question.status == "ASKED"
        ]),
        ("고객에게 공개된 처리 상태", request.customer_progress),
        ("고객에게 공개된 기관 확인 결과", request.published_verification_results),
        ("고객이 남긴 답변과 공개 사건 기록", request.known_facts),
        ("고객 공개 기록 검색 결과", request.retrieved_context),
        ("최근 고객 공개 대화", request.recent_conversation),
        ("고객 공개 첨부 요약", request.attachment_summaries),
        ("현재 고객 화면에서 사용할 수 있는 기능", [
            f"{capability}: {CUSTOMER_UI_CAPABILITIES[capability]}"
            for capability in request.customer_ui_capabilities
            if capability in CUSTOMER_UI_CAPABILITIES
        ]),
        ("서비스가 관리하는 공식 연락처", [
            f"{contact['label']}: {contact['number']}"
            for contact in CUSTOMER_SAFETY_CONTACTS
        ]),
    ]
    return "\n".join(
        f"[{name}]\n" + ("\n".join(f"- {item}" for item in values) if values else "- 없음")
        for name, values in sections
    )


