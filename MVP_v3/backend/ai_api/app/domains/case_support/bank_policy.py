def bank_instructions(request, repair_reason=None):
    instructions = BANK_PERSONA
    instructions += TASK_PLANNING if request.allow_task_planning else "\ntask_intents는 빈 배열입니다. 전달된 변경 처리 결과에 근거해 반영 내용과 다음 행동을 답하세요."
